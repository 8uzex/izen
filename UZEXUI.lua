                Text = string.upper(title), Font = Enum.Font.GothamBold, TextSize = 11,
                TextColor3 = Theme.SubText, Position = UDim2.fromOffset(14, 0),
                Size = UDim2.new(1, -14, 1, 0), Parent = f,
