            return { Set = function(_, t) l.Text = t end }
        end

        function Tab:AddButton(o)
            local b = New("TextButton", {
                Size = UDim2.new(1, 0, 0, 36), BackgroundColor3 = Theme.Element,
                Text = "", AutoButtonColor = false, Parent = Page,
